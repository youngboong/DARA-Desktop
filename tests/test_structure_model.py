@pytest.fixture(scope="module")
def sites(tmp_path_factory):
    path = tmp_path_factory.mktemp("cif") / "YFeO3.cif"
    path.write_text(YFEO3_CIF)
    return site_table(path)


def _ctx(**kw):
    base = {
        "weight_percent": 40.0,
        "narrow": False,
        "refinement_status": {"level": "high", "codes": []},
        "spacegroup_number": 62,
        "database_spacegroup_number": 62,
        "n_reflections": 88,
        "base_rwp": 5.0,
        "base_gof": 1.5,
    }
    return {**base, **kw}


def _fake(elements, free="xyz", multiplicity=4):
    return [
        {
            "index": i,
            "label": f"{e}{i}",
            "wyckoff": f"{multiplicity}a",
            "multiplicity": multiplicity,
            "species": [{"element": e, "occupancy": 1.0}],
            "xyz": [0.1, 0.2, 0.3],
            "free": list(free),
        }
        for i, e in enumerate(elements)
    ]


def _codes(result):
    return [r["code"] for r in result["refusals"]]


def test_site_table_yfeo3(sites):
    assert [(s["label"], s["wyckoff"], s["multiplicity"], s["free"]) for s in sites] == [
        ("Y1", "4c", 4, ["x", "z"]),
        ("Fe1", "4b", 4, []),
        ("O1", "4c", 4, ["x", "z"]),
        ("O2", "8d", 8, ["x", "y", "z"]),
    ]
    assert sites[1]["xyz"] == [0.0, 0.0, 0.5] and sites[0]["xyz"][1] == 0.25  # x, z: any equivalent position
    assert sites[0]["species"] == [{"element": "Y", "occupancy": 1.0}]


def test_apply_to_str_reproduces_v8_lines(sites):
    spec = {"positions": [0, 2, 3], "thermal": "fixed", "occupancy": [EXCHANGE]}
    out = apply_to_str(BASE_STR, spec, sites).split("\n")
    assert out[:7] == BASE_STR.split("\n")[:7]
    assert out[7:] == V8_LINES


def test_apply_to_str_b_overall_and_per_element(sites):
    out = apply_to_str(BASE_STR, {"thermal": "overall"}, sites)
    assert "GOAL=GrainSize(1,1,1) //\nPARAM=Ball=0.010000_0.001^0.04 //\nE=Y" in out
    assert out.count("TDS=Ball") == 4 and "TDS=0.01" not in out
    out = apply_to_str(BASE_STR, {"thermal": "per_element"}, sites)
    assert re.findall(r"PARAM=(B[A-Z]+)=", out) == ["BY", "BFE", "BO"]
    assert out.count("TDS=BO") == 2


def test_apply_to_str_substitution_vacancy_reset(sites):
    spec = {
        "occupancy": [
            {"kind": "substitution", "site": 1, "host": "Fe", "dopant": "Mn"},
            {"kind": "vacancy", "site": 0, "element": "Y"},
        ]
    }
    out = apply_to_str(BASE_STR, spec, sites)
    assert "PARAM=occ0=0.020000_0^0.3 //\nPARAM=occ1=0.950000_0.7^1 //\nE=(Y(occ1)) Wyckoff=c" in out
    assert "E=(FE,MN(occ0)) Wyckoff=b" in out
    assert apply_to_str(BASE_STR, {"reset": True, "phase": "x"}, sites) == BASE_STR


def test_validate_ok_counts(sites):
    spec = {"positions": [0, 2, 3], "thermal": "overall", "occupancy": [EXCHANGE]}
    result = validate(spec, sites, _ctx())
    assert result["refusals"] == []
    assert result["n_parameters"] == 2 + 2 + 3 + 1 + 1
    assert result["max_parameters"] == 12


def test_validate_hydrogen():
    result = validate({"positions": [1]}, _fake(["Li", "H"]), _ctx())
    assert _codes(result) == ["hydrogen"]


def test_validate_low_contrast_and_weak_warning():
    sites = _fake(["Co", "Ni", "Zn"])
    spec = {"occupancy": [{"kind": "exchange", "sites": [0, 1], "elements": ["Co", "Ni"]}]}
    assert _codes(validate(spec, sites, _ctx())) == ["low_contrast"]
    spec = {"occupancy": [{"kind": "exchange", "sites": [0, 2], "elements": ["Co", "Zn"]}]}
    result = validate(spec, sites, _ctx())
    assert result["refusals"] == [] and "Weak X-ray contrast" in result["warnings"][0]


def test_validate_too_many_parameters():
    result = validate({"positions": [0, 1, 2, 3, 4]}, _fake(["Fe"] * 5), _ctx())
    assert (result["n_parameters"], _codes(result)) == (15, ["too_many_parameters"])
    assert "15 requested, at most 12 allowed" in result["refusals"][0]["message"]
    # few reflections lower the limit
    few = validate({"positions": [0, 1]}, _fake(["Fe"] * 2), _ctx(n_reflections=20))
    assert _codes(few) == ["too_many_parameters"]


def test_validate_minor_phase_and_status_rules(sites):
    assert _codes(validate({}, sites, _ctx(weight_percent=3.0))) == ["minor_phase"]
    assert _codes(validate({}, sites, _ctx(narrow=True))) == ["minor_phase"]
    subgroup = _ctx(database_spacegroup_number=167, spacegroup_number=15)
    assert _codes(validate({}, sites, subgroup)) == ["subgroup_setting"]
    lattice = _ctx(refinement_status={"level": "medium", "codes": ["lattice_at_limit"]})
    assert _codes(validate({}, sites, lattice)) == ["lattice_not_stable"]
    assert _codes(validate({}, sites, _ctx(base_rwp=16.0))) == ["poor_base_fit"]
    minor = validate({"occupancy": [EXCHANGE]}, sites, _ctx(weight_percent=8.0))
    assert _codes(minor) == ["occupancy_minor"]


def test_validate_bad_site(sites):
    bad = {"occupancy": [{"kind": "vacancy", "site": 0, "element": "Li"}]}
    result = validate(bad, sites, _ctx())
    assert _codes(result) == ["bad_site"]
    assert result["refusals"][0]["message"] == "Site 0 does not contain Li."
    same = {"occupancy": [{"kind": "exchange", "sites": [0, 0], "elements": ["Y", "Y"]}]}
    assert "bad_site" in _codes(validate(same, sites, _ctx()))
    assert "bad_site" in _codes(validate({"positions": [9]}, sites, _ctx()))
